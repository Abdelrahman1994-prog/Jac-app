package com.jacdrive.core.model

/**
 * Every value the app can show. Each metric records where it is expected to come from so the UI
 * can be honest about provenance (ECU PID vs adapter vs app-calculated vs phone sensor).
 */
enum class VehicleMetric(val metricUnit: String, val staleAfterMs: Long) {
    SPEED("km/h", 2_000),
    RPM("rpm", 2_000),
    COOLANT_TEMP("°C", 10_000),
    BATTERY_VOLTAGE("V", 10_000),
    ENGINE_LOAD("%", 3_000),
    THROTTLE_POSITION("%", 3_000),
    FUEL_LEVEL("%", 60_000),
    INTAKE_AIR_TEMP("°C", 10_000),
    INTAKE_MANIFOLD_PRESSURE("kPa", 3_000),
    TIMING_ADVANCE("°", 3_000),
    TRIP_DISTANCE("km", 10_000),
    AVG_FUEL_CONSUMPTION("L/100km", 30_000),
}

/** Where a value originated. Simulated values must never be presented as real. */
enum class DataSource {
    /** Decoded from a standard OBD-II (SAE J1979) PID response from the ECU. */
    ECU,

    /** Measured by the OBD adapter itself (e.g. ELM327 `ATRV` supply voltage). */
    ADAPTER,

    /** Derived by the app from other real values (e.g. trip distance integrated from speed). */
    CALCULATED,

    /** Measured by the phone (accelerometer, GPS). */
    PHONE_SENSOR,

    /** Generated by the demo simulator. NOT vehicle data. */
    SIMULATED,
}

data class LiveValue(
    val value: Double,
    val timestampMs: Long,
    val source: DataSource,
) {
    fun ageMs(nowMs: Long): Long = (nowMs - timestampMs).coerceAtLeast(0)
}

enum class Freshness { LIVE, STALE, MISSING }

fun LiveValue?.freshness(metric: VehicleMetric, nowMs: Long): Freshness = when {
    this == null -> Freshness.MISSING
    ageMs(nowMs) > metric.staleAfterMs -> Freshness.STALE
    else -> Freshness.LIVE
}
